#!/usr/bin/env bash
# Fetch self-hosted woff2 fonts from the npm registry (Fontsource) into assets/fonts.
# Build-time only: the shipped site never touches the network.
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
dest="$here/assets/fonts"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

pkgs=(
  "@fontsource-variable/space-grotesk"
  "@fontsource-variable/rubik"
  "@fontsource-variable/noto-serif"
  "@fontsource-variable/noto-sans-sc"
  "@fontsource-variable/noto-sans-tc"
  "@fontsource-variable/noto-sans-jp"
  "@fontsource-variable/noto-sans-kr"
  "@fontsource-variable/noto-serif-sc"
  "@fontsource-variable/noto-serif-tc"
  "@fontsource-variable/noto-serif-jp"
  "@fontsource-variable/noto-serif-kr"
)

mkdir -p "$dest"

for pkg in "${pkgs[@]}"; do
  name="${pkg##*/}"
  ver="$(curl -fsSL "https://registry.npmjs.org/$pkg/latest" | python3 -c 'import sys,json;print(json.load(sys.stdin)["version"])')"
  tgz="$work/$name.tgz"
  echo "fetch $name@$ver"
  curl -fsSL -o "$tgz" "https://registry.npmjs.org/$pkg/-/$name-$ver.tgz"
  mkdir -p "$work/$name" "$dest/$name"
  tar -xzf "$tgz" -C "$work/$name" package/index.css
  tar -xzf "$tgz" -C "$dest/$name" --strip-components=2 'package/files/*.woff2'
done

# Concatenate every @font-face block, rewriting url() paths and family names.
{
  echo "/* Tutor self-hosted fonts. Generated by tools/fetch-fonts.sh. */"
  for pkg in "${pkgs[@]}"; do
    name="${pkg##*/}"
    echo "/* $name */"
    sed -E "s#url\(\./files/#url(./$name/#g" "$work/$name/package/index.css"
  done
} > "$dest/fonts.css"

# Drop the redundant " Variable" suffix so the brief's stacks resolve.
python3 - "$dest/fonts.css" <<'PY'
import re, sys
p = sys.argv[1]
s = open(p).read()
s = re.sub(r"font-family: '([^']+?) Variable'", r"font-family: '\1'", s)
open(p, "w").write(s)
PY

echo "files: $(find "$dest" -name '*.woff2' | wc -l | tr -d ' ')"
du -sh "$dest"
