import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = new URL('..', import.meta.url).pathname
const dir = join(root, 'apps/server/migrations')
const out = join(root, 'apps/server/src/db/migrations.gen.ts')

const files = readdirSync(dir)
  .filter((f) => f.endsWith('.sql'))
  .sort()

const entries = files
  .map(
    (name) =>
      `  { name: ${JSON.stringify(name)}, sql: ${JSON.stringify(readFileSync(join(dir, name), 'utf8'))} },`,
  )
  .join('\n')

const ts = `// AUTO-GENERATED by scripts/gen-migrations.mjs — do not edit by hand.\n// Embedded so the compiled binary can apply migrations without the source tree.\n\nexport const MIGRATIONS: { name: string; sql: string }[] = [\n${entries}\n]\n`

writeFileSync(out, ts)
console.log(`wrote ${files.length} migrations to ${out}`)
